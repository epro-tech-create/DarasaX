import type { TimetableEntry } from "@/types";
import { getModule } from "@/data/mock";

const DAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday"];
const START_MINUTES = 7 * 60;
const SLOT_MINUTES = 30;
const SLOT_COUNT = 28;

function timeLabel(minutes: number) {
  return `${String(Math.floor(minutes / 60)).padStart(2, "0")}:${String(minutes % 60).padStart(2, "0")}`;
}

export async function downloadTimetableXlsx(entries: TimetableEntry[], stream: string, from: string, to: string) {
  const { Workbook } = await import("exceljs");
  const workbook = new Workbook();
  workbook.creator = "DarasaX";
  workbook.title = `Teaching timetable - ${stream}`;
  const sheet = workbook.addWorksheet("Timetable", { views: [{ state: "frozen", ySplit: 3, xSplit: 1 }] });
  sheet.pageSetup = { orientation: "landscape", fitToPage: true, fitToWidth: 1, fitToHeight: 1, paperSize: 9 };
  sheet.columns = [{ width: 17 }, ...DAYS.map(() => ({ width: 31 }))];
  sheet.mergeCells("A1:F1");
  sheet.getCell("A1").value = "TEACHING TIMETABLE";
  sheet.getCell("A1").font = { bold: true, size: 16, color: { argb: "FFFFFFFF" } };
  sheet.getCell("A1").alignment = { horizontal: "center", vertical: "middle" };
  sheet.getCell("A1").fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF12324A" } };
  sheet.getRow(1).height = 30;
  sheet.mergeCells("A2:F2");
  sheet.getCell("A2").value = `${stream}  ·  ${from} to ${to}  ·  EAT`;
  sheet.getCell("A2").font = { bold: true, size: 11, color: { argb: "FF1677D2" } };
  sheet.getCell("A2").alignment = { horizontal: "center", vertical: "middle" };
  sheet.getRow(2).height = 22;
  const header = sheet.getRow(3);
  header.values = ["Time", ...DAYS];
  header.height = 24;
  header.eachCell(cell => {
    cell.font = { bold: true, color: { argb: "FFFFFFFF" } };
    cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF1677D2" } };
    cell.alignment = { horizontal: "center", vertical: "middle" };
    cell.border = { top: { style: "thin" }, bottom: { style: "thin" }, left: { style: "thin" }, right: { style: "thin" } };
  });

  for (let index = 0; index < SLOT_COUNT; index++) {
    const row = sheet.getRow(index + 4);
    row.height = 28;
    const start = START_MINUTES + index * SLOT_MINUTES;
    row.getCell(1).value = `${timeLabel(start)}–${timeLabel(start + SLOT_MINUTES)}`;
    row.getCell(1).font = { bold: true, size: 9 };
    row.getCell(1).alignment = { horizontal: "center", vertical: "middle" };
  }

  const sorted = [...entries].sort((a, b) => a.day - b.day || a.startTime.localeCompare(b.startTime));
  for (const entry of sorted) {
    const dayColumn = entry.day - 1;
    if (dayColumn < 0 || dayColumn > 4) continue;
    const start = Number(entry.startTime.slice(0, 2)) * 60 + Number(entry.startTime.slice(3, 5));
    const end = Number(entry.endTime.slice(0, 2)) * 60 + Number(entry.endTime.slice(3, 5));
    const first = Math.max(0, Math.floor((start - START_MINUTES) / SLOT_MINUTES));
    const last = Math.min(SLOT_COUNT, Math.ceil((end - START_MINUTES) / SLOT_MINUTES));
    if (last <= first) continue;
    const top = first + 4;
    const bottom = last + 3;
    const column = dayColumn + 2;
    const cell = sheet.getCell(top, column);
    const course = getModule(entry.moduleId);
    cell.value = [entry.status === "cancelled" ? "CANCELLED" : null, course?.name ?? entry.moduleId, course?.code, `${entry.startTime}–${entry.endTime}`, entry.lecturer, entry.room].filter(Boolean).join("\n");
    cell.alignment = { horizontal: "center", vertical: "middle", wrapText: true };
    cell.font = { size: 9, color: { argb: entry.status === "cancelled" ? "FFB42318" : "FF172B3A" } };
    if (bottom > top) sheet.mergeCells(top, column, bottom, column);
  }
  for (let row = 4; row < SLOT_COUNT + 4; row++) {
    for (let col = 1; col <= 6; col++) {
      const cell = sheet.getCell(row, col);
      cell.border = { top: { style: "thin", color: { argb: "FF555555" } }, bottom: { style: "thin", color: { argb: "FF555555" } }, left: { style: "thin", color: { argb: "FF555555" } }, right: { style: "thin", color: { argb: "FF555555" } } };
    }
  }
  sheet.mergeCells(`A${SLOT_COUNT + 4}:F${SLOT_COUNT + 4}`);
  sheet.getCell(`A${SLOT_COUNT + 4}`).value = "Timetable generated by DarasaX";
  sheet.getCell(`A${SLOT_COUNT + 4}`).alignment = { horizontal: "right" };
  const bytes = await workbook.xlsx.writeBuffer();
  const blob = new Blob([bytes as BlobPart], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = `DarasaX-${stream.replace(/[^A-Za-z0-9_-]/g, "_")}-timetable-${from}.xlsx`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 15000);
}
