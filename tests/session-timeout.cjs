const assert = require('node:assert/strict');
const fs = require('node:fs');
const root = fs.readFileSync('src/app/layout.tsx', 'utf8');
assert.doesNotMatch(root, /SessionTimeout|session-timeout/);
assert.equal(fs.existsSync('src/components/auth/session-timeout.tsx'), false);
assert.equal(fs.existsSync('src/lib/auth/idle-policy.ts'), false);
const client = fs.readFileSync('src/lib/supabase/client.ts', 'utf8');
assert.match(client, /persistSession: true/);
assert.match(client, /autoRefreshToken: true/);
console.log('Passed persistent sessions, automatic token refresh, and removal of inactivity logout for every portal.');
